import {
  DeleteObjectsCommand,
  GetObjectCommand,
  PutObjectCommand,
  S3Client,
} from "@aws-sdk/client-s3";
import type { Env } from "@ecom/config";

/**
 * Where uploaded files live. The application talks to this interface only, so
 * the storage service can be swapped (any S3-compatible service today) and
 * tests can run without one.
 *
 * Keys under `public/` are readable by anyone who knows the address; nothing
 * else in the bucket is. Listing the bucket is never allowed.
 */
export interface StorageProvider {
  put(key: string, body: Uint8Array, options: { contentType: string }): Promise<void>;
  get(key: string): Promise<Uint8Array>;
  /** Deletes the given files. Files that do not exist are ignored. */
  delete(keys: readonly string[]): Promise<void>;
  /** The address a browser uses to fetch a public file. */
  publicUrl(key: string): string;
}

export type StorageEnv = Pick<
  Env,
  | "S3_ENDPOINT"
  | "S3_REGION"
  | "S3_BUCKET"
  | "S3_ACCESS_KEY_ID"
  | "S3_SECRET_ACCESS_KEY"
  | "S3_PUBLIC_URL"
>;

/** Keys are generated by the application; this guards against a mistake, not an attacker. */
const SAFE_KEY = /^[A-Za-z0-9][A-Za-z0-9/_.-]*$/;

function assertKey(key: string): void {
  if (!SAFE_KEY.test(key) || key.includes("..") || key.includes("//")) {
    throw new Error("storage: invalid object key");
  }
}

export function publicUrlFor(baseUrl: string, key: string): string {
  assertKey(key);
  return `${baseUrl.replace(/\/+$/, "")}/${key}`;
}

/** Files never change once written (each upload gets a new key), so browsers may keep them. */
const IMMUTABLE = "public, max-age=31536000, immutable";

export function createS3Storage(env: StorageEnv): StorageProvider {
  const client = new S3Client({
    endpoint: env.S3_ENDPOINT,
    region: env.S3_REGION,
    forcePathStyle: true,
    credentials: {
      accessKeyId: env.S3_ACCESS_KEY_ID,
      secretAccessKey: env.S3_SECRET_ACCESS_KEY,
    },
  });
  return {
    async put(key, body, options) {
      assertKey(key);
      await client.send(
        new PutObjectCommand({
          Bucket: env.S3_BUCKET,
          Key: key,
          Body: body,
          ContentType: options.contentType,
          CacheControl: IMMUTABLE,
        }),
      );
    },
    async get(key) {
      assertKey(key);
      const result = await client.send(new GetObjectCommand({ Bucket: env.S3_BUCKET, Key: key }));
      if (!result.Body) throw new Error("storage: empty response");
      return result.Body.transformToByteArray();
    },
    async delete(keys) {
      if (keys.length === 0) return;
      keys.forEach(assertKey);
      await client.send(
        new DeleteObjectsCommand({
          Bucket: env.S3_BUCKET,
          Delete: { Objects: keys.map((Key) => ({ Key })), Quiet: true },
        }),
      );
    },
    publicUrl: (key) => publicUrlFor(env.S3_PUBLIC_URL, key),
  };
}

export interface MemoryStorage extends StorageProvider {
  readonly files: Map<string, { body: Uint8Array; contentType: string }>;
}

/** Keeps files in memory. For tests. */
export function createMemoryStorage(baseUrl = "https://media.example.test"): MemoryStorage {
  const files = new Map<string, { body: Uint8Array; contentType: string }>();
  return {
    files,
    async put(key, body, options) {
      assertKey(key);
      files.set(key, { body, contentType: options.contentType });
    },
    async get(key) {
      const file = files.get(key);
      if (!file) throw new Error("storage: no such file");
      return file.body;
    },
    async delete(keys) {
      for (const key of keys) files.delete(key);
    },
    publicUrl: (key) => publicUrlFor(baseUrl, key),
  };
}
